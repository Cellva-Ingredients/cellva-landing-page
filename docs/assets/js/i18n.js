const IDIOMA_PADRAO = "en";
const HTML_LANG = { en: "en", pt: "pt-BR", de: "de" };
const CHAVE_STORAGE = "cellva-idioma";

let idiomaAtual = IDIOMA_PADRAO;

function t(chave) {
  return I18N[idiomaAtual][chave] ?? I18N[IDIOMA_PADRAO][chave] ?? chave;
}

function aplicarIdioma(idioma) {
  if (!I18N[idioma]) idioma = IDIOMA_PADRAO;
  idiomaAtual = idioma;

  document.documentElement.lang = HTML_LANG[idioma];
  document.title = t("meta.title");
  document.querySelector('meta[name="description"]').setAttribute("content", t("meta.description"));

  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel)); });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => { el.alt = t(el.dataset.i18nAlt); });
  document.querySelectorAll("[data-i18n-value]").forEach((el) => { el.value = t(el.dataset.i18nValue); });

  const seletor = document.getElementById("idioma");
  if (seletor) seletor.value = idioma;

  document.dispatchEvent(new CustomEvent("idiomachange", { detail: idioma }));
}

function idiomaSalvo() {
  try { return localStorage.getItem(CHAVE_STORAGE); } catch (e) { return null; }
}

function salvarIdioma(idioma) {
  try { localStorage.setItem(CHAVE_STORAGE, idioma); } catch (e) { /* navegação privada: segue sem salvar */ }
}

aplicarIdioma(idiomaSalvo() || IDIOMA_PADRAO);

document.getElementById("idioma").addEventListener("change", (e) => {
  salvarIdioma(e.target.value);
  aplicarIdioma(e.target.value);
});
